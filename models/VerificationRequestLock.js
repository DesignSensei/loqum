// models/VerificationRequestLock.js

const mongoose = require("mongoose");

const LOCK_KEY_PATTERN = /^cac:[a-f0-9]{24}$/;
const OWNER_TOKEN_PATTERN = /^[a-f0-9]{64}$/;
const REQUEST_REFERENCE_PATTERN = /^[A-Za-z0-9_.:-]{1,128}$/;

/*
 * CAC VERIFICATION REQUEST LOCK
 *
 * Provides one durable verification lock per
 * employer profile.
 *
 * PURPOSE
 *
 * - Prevent concurrent paid CAC verification requests;
 * - Preserve ownership of an in-flight provider request;
 * - Support renewable processing leases;
 * - Prevent stale workers from completing or releasing
 *   another worker's lock;
 * - Preserve uncertain outcomes for manual reconciliation.
 *
 * LOCK POLICY
 *
 * A lock expiring does not prove that the external
 * provider request was unsuccessful.
 *
 * Expired locks must not be automatically deleted.
 *
 * An expired lock remains in the database until
 * an authorized reconciliation process releases it.
 *
 * The service owns atomic acquisition, renewal,
 * ownership fencing, release and reconciliation.
 */

const verificationRequestLockSchema = new mongoose.Schema(
  {
    // ───────────────────── LOCK IDENTITY ─────────────────────

    /*
     * The lock key is deterministic:
     *
     * cac:<employerProfileObjectId>
     *
     * MongoDB's _id uniqueness guarantees one lock
     * for each employer's CAC verification workflow.
     */

    _id: {
      type: String,
      required: true,
      immutable: true,
      match: [LOCK_KEY_PATTERN, "Invalid verification lock key."],
    },

    employer: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "EmployerProfile",
      required: true,
      immutable: true,
      index: true,
    },

    // ───────────────────── LOCK OWNERSHIP ─────────────────────

    /*
     * Generated by the verification service using
     * crypto.randomBytes(32).toString("hex").
     *
     * The owner token must never change while
     * the lock exists.
     *
     * Renewal and release must match this token.
     */

    ownerToken: {
      type: String,
      required: true,
      immutable: true,
      trim: true,
      match: [OWNER_TOKEN_PATTERN, "Invalid verification lock owner token."],
      select: false,
    },

    // ───────────────────── LOCK TIMESTAMPS ─────────────────────

    acquiredAt: {
      type: Date,
      required: true,
      immutable: true,
    },

    /*
     * The expiration timestamp is intentionally
     * mutable because an active lock may be renewed.
     *
     * No automatic TTL index must be created.
     */

    expiresAt: {
      type: Date,
      required: true,
    },

    renewedAt: {
      type: Date,
      default: null,
    },

    // ───────────────────── PROVIDER REQUEST CORRELATION ─────────────────────

    /*
     * The request reference identifies the exact
     * CAC verification request associated with
     * the lock.
     *
     * Administrative reconciliation must require
     * this reference before releasing an expired lock.
     *
     * It is generated server-side and must not
     * be replaced during the lock lifecycle.
     */

    requestReference: {
      type: String,
      required: true,
      immutable: true,
      trim: true,
      maxlength: 128,
      match: [REQUEST_REFERENCE_PATTERN, "Invalid CAC verification request reference."],
      select: false,
    },
  },
  {
    timestamps: true,
    versionKey: false,
    collection: "verification_request_locks",
  }
);

// ───────────────────── DOCUMENT VALIDATION ─────────────────────

verificationRequestLockSchema.pre("validate", function () {
  // ───────── LOCK KEY AND EMPLOYER CONSISTENCY ─────────

  if (this.employer && this._id) {
    const expectedKey = `cac:${String(this.employer._id || this.employer).toLowerCase()}`;

    if (this._id !== expectedKey) {
      this.invalidate("employer", "Employer ID does not match the verification lock key.");
    }
  }

  // ───────── INITIAL LEASE VALIDATION ─────────

  if (this.acquiredAt && this.expiresAt) {
    const acquiredAt = new Date(this.acquiredAt).getTime();
    const expiresAt = new Date(this.expiresAt).getTime();

    if (!Number.isFinite(acquiredAt) || !Number.isFinite(expiresAt) || expiresAt <= acquiredAt) {
      this.invalidate("expiresAt", "Lock expiration must be later than acquisition.");
    }
  }

  // ───────── RENEWAL VALIDATION ─────────

  if (this.renewedAt != null) {
    const renewedAt = new Date(this.renewedAt).getTime();
    const acquiredAt = this.acquiredAt ? new Date(this.acquiredAt).getTime() : NaN;
    const expiresAt = this.expiresAt ? new Date(this.expiresAt).getTime() : NaN;

    if (
      !Number.isFinite(renewedAt) ||
      !Number.isFinite(acquiredAt) ||
      !Number.isFinite(expiresAt) ||
      renewedAt < acquiredAt ||
      renewedAt >= expiresAt
    ) {
      this.invalidate(
        "renewedAt",
        "Lock renewal must occur after acquisition and before expiration."
      );
    }
  }
});

// ───────────────────── ATOMIC LOCK OPERATIONS ─────────────────────

/*
 * The verification service must enforce:
 *
 * ACQUISITION
 * - Create the deterministic lock key atomically.
 * - Reject duplicate acquisition attempts.
 * - Never overwrite an existing expired lock automatically.
 *
 * RENEWAL
 * - Match lock key and ownerToken.
 * - Require expiresAt to remain in the future.
 * - Update renewedAt and expiresAt together.
 *
 * OWNERSHIP FENCING
 * - Confirm lock ownership inside the transaction
 *   that persists the verification result.
 *
 * RELEASE
 * - Match both lock key and ownerToken.
 * - Release only after the request is safely resolved.
 *
 * RECONCILIATION
 * - Require authorized administrator access.
 * - Require the original requestReference.
 * - Reject reconciliation of an active lock.
 * - Preserve an audit record of the resolution.
 *
 * Mongoose document validation does not automatically
 * apply to every query-based update.
 *
 * These conditions must also be enforced through
 * atomic service-layer database operations.
 */

// ───────────────────── INDEX POLICY ─────────────────────

/*
 * The _id field already provides a unique index.
 *
 * The employer field is indexed for lookup convenience.
 *
 * Do not add a TTL index on expiresAt.
 *
 * Expired locks are retained because provider
 * outcomes may still require reconciliation.
 */

module.exports = mongoose.model("VerificationRequestLock", verificationRequestLockSchema);
